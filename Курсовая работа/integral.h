/* ====================================================================
   Заголовочный файл: integral.h
   Назначение: Объявляет прототип функции integral(), которая
              вычисляет определённый интеграл заданной функции
              на отрезке методом Симпсона с заданной точностью.
   Защищён от повторного включения с помощью "include guard".
   ==================================================================== */

/* Директива #ifndef проверяет, не был ли уже определён макрос
   INTEGRAL_H. Если не был — файл ещё не подключался, и его
   содержимое можно безопасно обрабатывать. */
#ifndef INTEGRAL_H

/* Определяем макрос INTEGRAL_H, чтобы при повторных попытках
   подключить этот файл (например, из main.c и из integral.c)
   содержимое не дублировалось и не вызвало ошибок переопределения. */
#define INTEGRAL_H

/* --------------------------------------------------------------------
   Подключение functions.h.
   --------------------------------------------------------------------
   Нужно только ради одной вещи: получить определение типа func_t
   (указатель на функцию double (*)(double)), который используется
   в сигнатуре integral().
   functions.h сам защищён от повторного включения своим собственным
   include guard, поэтому конфликтов не возникнет.
   -------------------------------------------------------------------- */
#include "functions.h"   /* для типа func_t */

/* --------------------------------------------------------------------
   Прототип функции integral().
   --------------------------------------------------------------------
   Параметры:
     f    — указатель на подынтегральную функцию (тип func_t,
            объявленный в functions.h как double (*)(double)).
     a    — нижний предел интегрирования.
     b    — верхний предел интегрирования (предполагается b > a).
     eps2 — требуемая точность результата.

   Метод вычисления:
     Метод Симпсона (приближение функции параболами по три точки).
     Число отрезков разбиения удваивается на каждой итерации
     (2, 4, 8, 16, ...) до достижения заданной точности.

   Оценка точности — по правилу Рунге:
     |I_new − I_old| / 15 < eps2,
     где I_new — значение интеграла при удвоенном числе отрезков,
     I_old  — значение при прежнем (меньшем) числе отрезков.
     Множитель 15 возникает из порядка точности метода Симпсона
     (четвёртый порядок: 2^4 − 1 = 15).

   Возвращает:
     Приближённое значение определённого интеграла от f на [a, b]
     с точностью не хуже eps2 (или лучшее из достигнутых, если
     процесс не сошёлся за лимит итераций).

   Реализация находится в integral.c.
   -------------------------------------------------------------------- */
double integral(func_t f, double a, double b, double eps2);

/* Директива #endif закрывает блок #ifndef INTEGRAL_H.
   Всё содержимое между #ifndef и #endif обрабатывается
   компилятором только при первом включении файла. */
#endif /* INTEGRAL_H */
