/* Подключение собственного заголовочного файла, в котором объявлен
   тип func_t и прототип функции integral().
   Двойные кавычки означают, что файл ищется в той же директории. */
#include "integral.h"

/* Подключение стандартной математической библиотеки.
   Используется для вызова fabs() — функции, возвращающей
   абсолютное значение (модуль) числа типа double. */
#include <math.h>

/* ====================================================================
   Функция: integral
   Назначение: Вычисление определённого интеграла функции f на отрезке
              [a, b] методом Симпсона с заданной точностью eps2.
   Метод: Метод Симпсона (парабол) с автоматическим удвоением числа
          отрезков до достижения требуемой точности.
          Точность оценивается по правилу Рунге.
   Параметры:
     f    — указатель на подинтегральную функцию (тип func_t).
     a, b — пределы интегрирования (a < b).
     eps2 — требуемая точность результата.
   Возвращает: приближённое значение определённого интеграла.
   ==================================================================== */
double integral(func_t f, double a, double b, double eps2)
{
    /* n — текущее число отрезков разбиения отрезка [a, b].
       Метод Симпсона требует, чтобы n было чётным (формула
       аппроксимирует функцию параболами по три точки).
       Начинаем с минимального чётного значения n = 2. */
    int n = 2;

    /* h — шаг сетки (длина одного отрезка).
       Вычисляется как длина всего отрезка [a, b], делённая на n.
       При n = 2 получаем h = (b − a) / 2. */
    double h = (b - a) / n;

    /* ----------------------------------------------------------------
       Идея метода Симпсона: интеграл ≈ (h/3) * [f(x₀) + f(xₙ) +
       4 * (сумма в нечётных узлах) + 2 * (сумма в чётных узлах)].
       Чтобы не пересчитывать все суммы заново при каждом удвоении n,
       суммы накапливаются и переиспользуются.
       ---------------------------------------------------------------- */

    /* S1 — сумма значений функции на концах отрезка: f(a) + f(b).
       Эти значения не меняются при удвоении n, вычисляются один раз. */
    double S1 = f(a) + f(b);

    /* S2 — сумма значений функции в нечётных узлах (узлы с
       нечётными индексами i = 1, 3, 5, ...).
       При n = 2 единственный нечётный узел — это i = 1,
       координата которого равна a + h = a + (b−a)/2 (середина отрезка). */
    double S2 = f(a + h);

    /* S3 — сумма значений функции в чётных внутренних узлах
       (узлы с чётными индексами i = 2, 4, 6, ...).
       При n = 2 чётных внутренних узлов нет, поэтому S3 = 0. */
    double S3 = 0.0;

    /* I_prev — значение интеграла, полученное на текущем шаге.
       Формула Симпсона: I = (h/3) * (S1 + 4*S2 + 2*S3).
       Это первое приближение при n = 2 (одна парабола на весь отрезок). */
    double I_prev = h / 3.0 * (S1 + 4.0 * S2 + 2.0 * S3);

    /* ----------------------------------------------------------------
       Главный цикл: удваиваем n и пересчитываем интеграл,
       пока разница между последовательными приближениями
       не станет меньше заданной точности eps2.
       Ограничение n < 1000000 — защита от бесконечного цикла
       (например, если функция имеет разрыв или особенности).
       ---------------------------------------------------------------- */
    while (n < 1000000) {

        /* Удваиваем число отрезков: n = 4, 8, 16, 32, ... */
        n *= 2;

        /* Пересчитываем шаг h для нового числа отрезков.
           С каждым удвоением n шаг уменьшается вдвое. */
        h = (b - a) / n;

        /* Все узлы, которые были нечётными на предыдущем шаге,
           становятся чётными на текущем (их индексы удваиваются).
           Поэтому старую сумму S2 (нечётные узлы) прибавляем к S3
           (чётные узлы) — переиспользуем уже вычисленные значения. */
        S3 += S2;

        /* Обнуляем S2 — теперь сюда будут накапливаться значения
           только в новых нечётных узлах, появившихся при удвоении n. */
        S2 = 0.0;

        /* Перебираем только новые (нечётные) узлы: i = 1, 3, 5, ...
           Это узлы, которых не было на предыдущей сетке.
           Координата i-го узла вычисляется как a + i * h.
           Накапливаем сумму значений функции в этих узлах. */
        for (int i = 1; i < n; i += 2)
            S2 += f(a + i * h);

        /* Вычисляем новое значение интеграла по формуле Симпсона
           с обновлёнными суммами S1, S2, S3. */
        double I = h / 3.0 * (S1 + 4.0 * S2 + 2.0 * S3);

        /* Правило Рунге для оценки погрешности.
           Для метода Симпсона (порядок точности O(h^4))
           разница между двумя последовательными приближениями
           I (шаг h) и I_prev (шаг 2h) связана с погрешностью
           соотношением: |I − I_prev| / 15 < eps2.
           Множитель 15 = 2^4 − 1 появляется из порядка метода
           (четвёртый порядок точности: 2^4 = 16, 16 − 1 = 15).
           Если условие выполнено — точность достигнута. */
        if (fabs(I - I_prev) / 15.0 < eps2)
            return I;   /* Возвращаем результат с достигнутой точностью */

        /* Запоминаем текущее значение как «предыдущее»
           для сравнения на следующей итерации цикла. */
        I_prev = I;
    }

    /* Если цикл завершился по ограничению n < 1000000 (точность
       не достигнута за разумное число шагов), возвращаем последнее
       вычисленное значение. Это может произойти при интегрировании
       функций с особенностями или при слишком жёстком eps2. */
    return I_prev;
}
