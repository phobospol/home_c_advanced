/* ====================================================================
   Заголовочный файл: functions.h
   Назначение: Объявляет тип указателя на функцию и прототипы всех
              математических функций, используемых в программе
              (исходные функции, их производные, вспомогательные
              разности и производные разностей).
   Защищён от повторного включения с помощью "include guard".
   ==================================================================== */

/* Директива #ifndef проверяет, не был ли уже определён макрос
   FUNCTIONS_H. Если не был — значит, файл ещё не подключался,
   и мы можем безопасно обработать его содержимое. */
#ifndef FUNCTIONS_H

/* Определяем макрос FUNCTIONS_H, чтобы при повторных попытках
   подключить этот файл (например, из разных .c-модулей) содержимое
   не дублировалось и не вызвало ошибок переопределения. */
#define FUNCTIONS_H

/* --------------------------------------------------------------------
   Тип указателя на функцию.
   --------------------------------------------------------------------
   Объявляем новый тип func_t — указатель на функцию, которая
   принимает один аргумент типа double и возвращает double.
   Синтаксис: double (*func_t)(double)
   Это позволяет передавать функции (f1, f2, f3 и др.) как аргументы
   в другие функции — root() и integral(), — что требуется по заданию.
   -------------------------------------------------------------------- */
typedef double (*func_t)(double);

/* --------------------------------------------------------------------
   Прототипы исходных функций (кривых, ограничивающих область).
   Каждый прототип — это объявление без тела; реализация находится
   в functions.c. Прототип позволяет компилятору проверять
   правильность вызова (типы и количество аргументов) до линковки.
   -------------------------------------------------------------------- */

/* f1(x) = 0.6x + 3 — прямая (линейная функция).
   Параметр x — точка, в которой вычисляется значение.
   Возвращает значение функции в точке x. */
double f1(double x);

/* f2(x) = (x − 2)^3 − 1 — кубическая парабола.
   Сдвинута вправо на 2 и вниз на 1. */
double f2(double x);

/* f3(x) = 3 / x — гипербола.
   Не определена при x = 0. */
double f3(double x);

/* --------------------------------------------------------------------
   Прототипы производных исходных функций.
   Нужны для комбинированного метода (хорды + касательные) в root().
   -------------------------------------------------------------------- */

/* f1'(x) = 0.6 — производная константы-наклона прямой. */
double df1(double x);

/* f2'(x) = 3(x − 2)^2 — производная кубической параболы
   по правилу d/dx[(x−a)^3] = 3(x−a)^2. */
double df2(double x);

/* f3'(x) = −3/x^2 — производная гиперболы
   по правилу d/dx[3x^(−1)] = −3x^(−2). */
double df3(double x);

/* --------------------------------------------------------------------
   Прототипы вспомогательных функций (разностей).
   --------------------------------------------------------------------
   Каждая функция равна разности двух исходных.
   Нуль такой функции означает равенство двух кривых, то есть
   точку их пересечения. Поиск нулей выполняется в root().

   F1 = f3 − f1  →  пересечение гиперболы f3 и прямой f1
   F2 = f3 − f2  →  пересечение гиперболы f3 и параболы f2
   F3 = f2 − f1  →  пересечение параболы f2 и прямой f1
   -------------------------------------------------------------------- */

double F1(double x);  /* F1(x) = f3(x) − f1(x) */
double F2(double x);  /* F2(x) = f3(x) − f2(x) */
double F3(double x);  /* F3(x) = f2(x) − f1(x) */

/* --------------------------------------------------------------------
   Прототипы производных вспомогательных функций.
   --------------------------------------------------------------------
   Вычисляются как разность производных исходных функций
   (по правилу производной разности: (f − g)' = f' − g').
   Используются в root() для определения, с какого конца отрезка
   применять метод касательных.

   dF1 = df3 − df1  →  производная F1
   dF2 = df3 − df2  →  производная F2
   dF3 = df2 − df1  →  производная F3
   -------------------------------------------------------------------- */

double dF1(double x);  /* dF1(x) = df3(x) − df1(x) */
double dF2(double x);  /* dF2(x) = df3(x) − df2(x) */
double dF3(double x);  /* dF3(x) = df2(x) − df1(x) */

/* Директива #endif закрывает блок #ifndef FUNCTIONS_H.
   Всё содержимое между #ifndef и #endif обрабатывается только
   при первом включении файла. */
#endif /* FUNCTIONS_H */
