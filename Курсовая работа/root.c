/* Подключение собственного заголовочного файла, в котором объявлен
   прототип функции root() и глобальная переменная root_iterations.
   Двойные кавычки означают, что файл ищется в той же директории. */
#include "root.h"

/* Подключение стандартной библиотеки ввода-вывода.
   Используется для fprintf() — вывода сообщения об ошибке в поток
   stderr (стандартный поток ошибок), если на отрезке нет корня. */
#include <stdio.h>

/* Подключение стандартной математической библиотеки.
   Используется для вызова fabs() — функции, возвращающей
   абсолютное значение (модуль) числа типа double. */
#include <math.h>

/* ====================================================================
   Глобальная переменная: root_iterations
   Назначение: Хранит количество итераций, затраченных при последнем
              вызове функции root(). Используется основной программой
              для отчёта о количестве итераций по требованию опции
              командной строки --print-iterations.
   Область видимости: Весь проект (extern-объявление в root.h).
   ==================================================================== */
int root_iterations = 0;

/* ====================================================================
   Функция: root
   Назначение: Поиск корня уравнения f(x) = g(x) на отрезке [a, b]
              комбинированным методом (хорды + касательные) с
              заданной точностью eps1.
   Параметры:
     f, g   — указатели на функции (тип func_t, объявленный в functions.h).
     a, b   — концы отрезка, на котором ищется корень.
              Знаки f(a)−g(a) и f(b)−g(b) должны различаться.
     eps1   — требуемая точность по оси x.
     df, dg — указатели на производные функций f и g (нужны для
              метода касательных).
   Возвращает: Приближённое значение корня.
   ==================================================================== */
double root(func_t f, func_t g, double a, double b, double eps1,
            func_t df, func_t dg)
{
    /* Обнуляем счётчик итераций в начале каждого вызова root().
       Это глобальная переменная, объявленная выше. */
    root_iterations = 0;

    /* ----------------------------------------------------------------
       Подготовка: вычисляем значения F(x) = f(x) − g(x) на концах
       отрезка. Нуль функции F(x) — это точка пересечения f(x) и g(x).
       ---------------------------------------------------------------- */

    /* Fa — значение функции F в точке a: F(a) = f(a) − g(a). */
    double Fa = f(a) - g(a);

    /* Fb — значение функции F в точке b: F(b) = f(b) − g(b). */
    double Fb = f(b) - g(b);

    /* ----------------------------------------------------------------
       Проверка краевых случаев и наличия корня.
       ---------------------------------------------------------------- */

    /* Если F(a) = 0, то a уже является корнем — возвращаем a. */
    if (Fa == 0.0) return a;

    /* Если F(b) = 0, то b уже является корнем — возвращаем b. */
    if (Fb == 0.0) return b;

    /* Если F(a) и F(b) одного знака (произведение положительное),
       то теорема Больцано-Коши не гарантирует наличия корня на [a, b].
       Выводим предупреждение в stderr и возвращаем a как fallback. */
    if (Fa * Fb > 0.0) {
        fprintf(stderr, "root: на отрезке [%.6f, %.6f] нет смены знака\n",
                a, b);
        return a;
    }

    /* ----------------------------------------------------------------
       Основной цикл комбинированного метода.
       ----------------------------------------------------------------
       Метод сочетает:
       — Метод хорд (секущих): аппроксимирует функцию прямой, проведённой
         через точки на концах текущего отрезка. Пересечение этой прямой
         с осью x даёт новое приближение корня.
       — Метод касательных (Ньютона): проводит касательную к графику
         функции в одной из точек и берёт её пересечение с осью x.
       Касательные применяются с того конца, где F(x) * F'(x) > 0
       (касательная «врезается» в график и направлена к корню).
       Хорда применяется с противоположного конца.
       ---------------------------------------------------------------- */

    /* Цикл продолжается, пока длина отрезка [a, b] больше eps1.
       Когда отрезок становится короче eps1, середина отрезка
       принимается за корень с нужной точностью. */
    while (fabs(b - a) > eps1) {

        /* Увеличиваем счётчик итераций на 1. */
        root_iterations++;

        /* Пересчитываем значения F на текущих концах отрезка
           (a и b меняются на каждой итерации). */
        Fa = f(a) - g(a);
        Fb = f(b) - g(b);

        /* Вычисляем значения производной F'(x) = f'(x) − g'(x)
           на концах отрезка. Нужны для метода касательных. */
        double dFa = df(a) - dg(a);
        double dFb = df(b) - dg(b);

        /* Переменные для новых приближений корня:
           x_newton — приближение по методу касательных (Ньютона),
           x_chord  — приближение по методу хорд. */
        double x_newton, x_chord;

        /* ----------------------------------------------------------------
           Выбор стратегии: с какого конца применять касательные.
           ----------------------------------------------------------------
           Если F(b) * F'(b) > 0, то касательную проводим из точки b,
           а хорду — из точки a. Это гарантирует, что касательная
           приближается к корню с «правильной» стороны (монотонно).
           В противном случае — наоборот.
           ---------------------------------------------------------------- */
        if (Fb * dFb > 0.0) {

            /* --- Случай 1: касательные из b, хорда из a --- */

            /* Защита от деления на ноль: если производная в точке b
               практически равна нулю, дальнейшие вычисления невозможны
               (касательная горизонтальна). Прерываем цикл. */
            if (fabs(dFb) < 1e-15) break;

            /* Защита от деления на ноль: если значения функции на
               концах отрезка равны (прямая горизонтальна), хорда
               не пересекает ось x. Прерываем цикл. */
            if (fabs(Fb - Fa) < 1e-15) break;

            /* Метод касательных (Ньютона) из точки b:
               x_new = x − F(x) / F'(x).
               Формула: b_new = b − F(b) / F'(b). */
            x_newton = b - Fb / dFb;

            /* Метод хорд из точки a:
               x_new = x − F(x) * (b − a) / (F(b) − F(a)).
               Формула: a_new = a − F(a) * (b − a) / (F(b) − F(a)). */
            x_chord  = a - Fa * (b - a) / (Fb - Fa);

            /* Обновляем концы отрезка:
               a становится приближением по хорде,
               b становится приближением по касательной. */
            a = x_chord;
            b = x_newton;

        } else {

            /* --- Случай 2: касательные из a, хорда из b --- */

            /* Аналогичные защиты от деления на ноль. */
            if (fabs(dFa) < 1e-15) break;
            if (fabs(Fb - Fa) < 1e-15) break;

            /* Метод касательных (Ньютона) из точки a:
               x_new = a − F(a) / F'(a). */
            x_newton = a - Fa / dFa;

            /* Метод аппроксимации хордой из точки b:
               x_new = b − F(b) * (b − a) / (F(b) − F(a)).
               Примечание: в классической реализации хорда проводится
               из точки b, которая «закреплена», а приближение ищется
               на стороне a. */
            x_chord  = b - Fb * (b - a) / (Fb - Fa);

            /* Обновляем концы отрезка:
               a становится приближением по касательной,
               b становится приближением по хорде. */
            a = x_newton;
            b = x_chord;
        }
    }

    /* После выхода из цикла a и b достаточно близки друг к другу.
       Корень принимается равным середине отрезка [a, b]:
       x_root = (a + b) / 2.
       Это обеспечивает точность не хуже eps1 / 2 по оси x. */
    return (a + b) / 2.0;
}
