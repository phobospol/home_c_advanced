/* Подключение собственного заголовочного файла, в котором объявлены
   тип func_t и прототипы всех функций (f1, f2, f3, df1, df2, df3,
   F1, F2, F3, dF1, dF2, dF3). Двойные кавычки означают, что файл
   ищется в той же директории, что и текущий исходник. */
#include "functions.h"

/* Подключение стандартной математической библиотеки.
   В данном файле напрямую функции из <math.h> не вызываются,
   но подключение оставлено для совместимости и возможных будущих
   расширений (например, использования pow(), fabs() и т. д.). */
#include <math.h>

/* ====================================================================
   Исходные функции — те самые кривые, ограничивающие область,
   площадь которой нужно найти.
   ==================================================================== */

/* f1(x) = 0.6x + 3 — линейная функция (прямая).
   Принимает один аргумент x типа double.
   Возвращает значение 0.6 * x + 3.0. */
double f1(double x)  { return 0.6 * x + 3.0; }

/* f2(x) = (x − 2)^3 − 1 — кубическая парабола, сдвинутая вправо на 2
   и вниз на 1.
   Локальная переменная t = x − 2.0 используется, чтобы избежать
   многократного вычитания и сделать выражение компактнее.
   t * t * t — это t в кубе (быстрее, чем вызов pow(t, 3)). */
double f2(double x)  { double t = x - 2.0; return t * t * t - 1.0; }

/* f3(x) = 3 / x — гипербола.
   Внимание: при x = 0 функция не определена (деление на ноль),
   поэтому при поиске корней и интегрировании отрезки подбираются
   так, чтобы x = 0 в них не попадал. */
double f3(double x)  { return 3.0 / x; }

/* ====================================================================
   Производные исходных функций — нужны для комбинированного метода
   (хорды + касательные) в функции root().
   ==================================================================== */

/* df1(x) = 0.6 — производная от f1(x) = 0.6x + 3.
   Константа, не зависит от x.
   Конструкция (void)x; — стандартный приём, чтобы подавить
   предупреждение компилятора о неиспользуемом параметре x. */
double df1(double x) { (void)x; return 0.6; }

/* df2(x) = 3(x − 2)^2 — производная от f2(x) = (x − 2)^3 − 1.
   Правило дифференцирования: d/dx[(x − 2)^3] = 3(x − 2)^2.
   Снова используем t = x − 2.0 для краткости. */
double df2(double x) { double t = x - 2.0; return 3.0 * t * t; }

/* df3(x) = −3 / x^2 — производная от f3(x) = 3 / x.
   Правило: d/dx[3/x] = d/dx[3x^(−1)] = −3x^(−2) = −3/x^2.
   x * x в знаменателе — это x^2 (быстрее, чем вызов pow(x, 2)). */
double df3(double x) { return -3.0 / (x * x); }

/* ====================================================================
   Вспомогательные функции (разности).
   Каждая равна разности двух исходных функций.
   Нули этих функций — это абсциссы точек пересечения кривых.
   ==================================================================== */

/* F1(x) = f3(x) − f1(x).
   Корень F1(x) = 0 означает f3(x) = f1(x), то есть точку пересечения
   гиперболы f3 и прямой f1. */
double F1(double x)  { return f3(x) - f1(x); }

/* F2(x) = f3(x) − f2(x).
   Корень F2(x) = 0 означает f3(x) = f2(x), то есть точку пересечения
   гиперболы f3 и кубической параболы f2. */
double F2(double x)  { return f3(x) - f2(x); }

/* F3(x) = f2(x) − f1(x).
   Корень F3(x) = 0 означает f2(x) = f1(x), то есть точку пересечения
   кубической параболы f2 и прямой f1. */
double F3(double x)  { return f2(x) - f1(x); }

/* ====================================================================
   Производные вспомогательных функций — нужны для комбинированного
   метода в root(). Вычисляются как разность производных исходных
   функций (по правилу производной разности).
   ==================================================================== */

/* dF1(x) = f3'(x) − f1'(x) = df3(x) − df1(x).
   Используется для определения направления касательной при поиске
   корня уравнения F1(x) = 0. */
double dF1(double x) { return df3(x) - df1(x); }

/* dF2(x) = f3'(x) − f2'(x) = df3(x) − df2(x).
   Используется для поиска корня уравнения F2(x) = 0. */
double dF2(double x) { return df3(x) - df2(x); }

/* dF3(x) = f2'(x) − f1'(x) = df2(x) − df1(x).
   Используется для поиска корня уравнения F3(x) = 0. */
double dF3(double x) { return df2(x) - df1(x); }
