/* ====================================================================
   Заголовочный файл: root.h
   Назначение: Объявляет прототип функции root() для поиска корней
              уравнений и extern-объявление глобальной переменной
              root_iterations для подсчёта итераций.
   Защищён от повторного включения с помощью "include guard".
   ==================================================================== */

/* Директива #ifndef проверяет, не был ли уже определён макрос
   ROOT_H. Если не был — файл ещё не подключался, и его содержимое
   можно безопасно обрабатывать. */
#ifndef ROOT_H

/* Определяем макрос ROOT_H, чтобы при повторных попытках подключить
   этот файл (например, из main.c и из root.c) содержимое не
   дублировалось и не вызвало ошибок переопределения. */
#define ROOT_H

/* --------------------------------------------------------------------
   Подключение functions.h.
   --------------------------------------------------------------------
   Нужно для получения определения типа func_t — указателя на функцию
   double (*)(double). Этот тип используется в сигнатуре root()
   для передачи функций и их производных как аргументов.
   functions.h сам защищён от повторного включения, поэтому
   конфликтов при многократном подключении не возникнет.
   -------------------------------------------------------------------- */
#include "functions.h"   /* для типа func_t */

/* --------------------------------------------------------------------
   Объявление глобальной переменной root_iterations.
   --------------------------------------------------------------------
   Ключевое слово extern означает, что переменная определена
   (создана и инициализирована) в другом файле — root.c, — а здесь
   лишь объявляется её существование и тип. Это позволяет другим
   модулям (например, main.c) читать значение этой переменной
   после вызова root(), чтобы вывести число итераций.

   Назначение: хранит количество итераций, затраченных при
   последнем вызове функции root(). Основная программа читает
   это значение, если задана опция --print-iterations.
   -------------------------------------------------------------------- */
extern int root_iterations;

/* --------------------------------------------------------------------
   Прототип функции root().
   --------------------------------------------------------------------
   Назначение: Поиск корня уравнения f(x) = g(x) на отрезке [a, b]
              комбинированным методом (хорды + касательные) с
              заданной точностью eps1.

   Параметры:
     f, g   — указатели на функции (тип func_t). Уравнение f(x) = g(x)
              преобразуется к виду F(x) = f(x) − g(x) = 0.
     a, b   — концы отрезка, на котором ищется корень.
              Обязательное условие: знаки f(a)−g(a) и f(b)−g(b)
              должны различаться (смена знака гарантирует корень
              по теореме Больцано-Коши).
     eps1   — требуемая точность по оси x. Цикл продолжается,
              пока длина отрезка [a, b] превышает eps1.
     df, dg — указатели на производные функций f и g (тип func_t).
              Нужны для метода касательных (Ньютона), который
              использует формулу x_new = x − F(x) / F'(x).

   Возвращает:
     Приближённое значение корня — середину final-отрезка [a, b]:
     x_root = (a + b) / 2.

   Побочный эффект:
     После возврата из функции глобальная переменная root_iterations
     содержит количество итераций, затраченных на поиск данного
     корня. Это значение можно прочитать из других модулей.

   Реализация находится в root.c.
   -------------------------------------------------------------------- */
double root(func_t f, func_t g, double a, double b, double eps1,
            func_t df, func_t dg);

/* Директива #endif закрывает блок #ifndef ROOT_H.
   Всё содержимое между #ifndef и #endif обрабатывается
   компилятором только при первом включении файла. */
#endif /* ROOT_H */
