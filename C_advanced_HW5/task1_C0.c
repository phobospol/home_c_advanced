#include <stdio.h>
#include <string.h>

/*
Вычеркивание
Сколько различных трехзначных чисел можно получить из заданного натурального N, вычеркивая цифры из его десятичной записи?
*/

int main()
{
    char s[10001]; // Объявляем массив символов (строку) размером 10001, один символ резервируется под признак конца строки '\0'. Сюда мы прочитаем исходное число N как строку. Символьный массив нужен для больших чисел.
    if (scanf("%10000s", s) != 1) //  Проверяем, что scanf успешно считал ровно одину  строку
    {
        return 1;
    }
    int len = (int)strlen(s); // Количество цифр в исходной строке (числе)

    int count = 0; // Счётчик различных трёхзначных чисел, которые можно получить

    // Перебираем все трёхзначные числа от 100 до 999. Для каждого из них мы проверим, можно ли его получить из исходной строки вычёркиванием лишних цифр.
    for (int num = 100; num <= 999; ++num)
    {
        int d1 = num / 100;        // сотни
        int d2 = (num / 10) % 10;  // десятки
        int d3 = num % 10;         // единицы

        int pos = 0; // Текущая позиция в строке, с которой мы ищем очередную цифру. Начинаем с 0 — с первого символа.

        // Ищем d1
        while (pos < len && s[pos] - '0' != d1) pos++; // s[pos] - '0' превращает символ-цифру в число пока текущий символ не равен d1
        if (pos >= len) continue; // Если d1 не найдена (дошли до конца строки), это трёхзначное число получить нельзя. continue переходит к следующему num в цикле for
        pos++;

        // Ищем d2 (начиная со следующей позиции после d1)
        while (pos < len && s[pos] - '0' != d2) pos++;
        if (pos >= len) continue;
        pos++;

        // Ищем d3 (начиная со следующей позиции после d2)
        while (pos < len && s[pos] - '0' != d3) pos++;
        if (pos >= len) continue;

        // Все три цифры найдены в нужном порядке — число можно получить
        count++;
    }

    printf("%d\n", count);
    return 0;
}
