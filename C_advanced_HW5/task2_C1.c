#include <stdio.h>
#include <string.h>

/* Префикс и суффикс.
На стандартном потоке ввода задаются две символьные строки, разделённые символом перевода строки. Каждая из строк не превышает по длине 10000 символов.
В строках не встречаются пробельные символы. На стандартный поток вывода напечатайте два числа, разделённых пробелом: первое число — длина наибольшего префикса первой строки,
являющегося суффиксом второй; второе число — наоборот, длина наибольшего суффикса первой строки, являющегося префиксом второй. Сравнение символов проводите с учётом регистра
(т.е. символы 'a' и 'A' различны).
*/

#define MAXLEN 10002  // Объявляет константу MAXLEN = 10002. Плюс fgets может сохранить символ перевода строки \n, плюс нужен завершающий нулевой байт \0. 10000 символов + '\n' + '\0'

static int pi[MAXLEN]; // Глобальный массив для префикс‑функции (алгоритм КМП).

// Функция compute_prefix — префикс‑функция, принимает указатель на строку pat и её длину m
void compute_prefix(const char *pat, int m)
{
    pi[0] = 0; // Для подстроки длины 1 нет непустого префикса, совпадающего с суффиксом, поэтому pi[0] = 0
    int k = 0; // Хранит длину текущего совпадения префикса и суффикса
    for (int i = 1; i < m; i++) // Цикл по строке, начиная со второго символа (индекс 1) до конца. На каждой итерации вычисляем pi[i].
    {
        while (k > 0 && pat[k] != pat[i]) // Если текущий символ pat[i] не совпадает с ожидаемым pat[k], откатываемся по уже посчитанным значениям префикс‑функции
            k = pi[k - 1];
        if (pat[k] == pat[i]) // Если символы совпали, увеличиваем длину совпадения
            k++;
        pi[i] = k; // Записываем в массив результат: длина наибольшего собственного префикса подстроки pat[0..i], который совпадает с её суффиксом
    }
}

// Функция kmp_match_end — ищет наибольший префикс одной строки, который является суффиксом другой
int kmp_match_end(const char *pat, int m, const char *txt, int n)
{
    if (m == 0 || n == 0) // Если одна из строк пустая, никакого совпадения быть не может. Сразу возвращаем 0
        return 0;

    compute_prefix(pat, m); // Строим префикс‑функцию для шаблона pat

    int j = 0; // значение текущей длины совпадения между префиксом pat и суффиксом уже прочитанной части txt
    for (int i = 0; i < n; i++) // Проходим по всем символам текста txt
    {
        if (j == m) // Если набрали полное совпадение с шаблоном, откатываемся ищем суффикс всего текста
            j = pi[j - 1];

        while (j > 0 && pat[j] != txt[i]) // При несовпадении символов откатываемся по префикс‑функции pat, чтобы не терять уже найденные совпадения
            j = pi[j - 1];

        if (pat[j] == txt[i]) // Если символы совпали, увеличиваем текущую длину совпадения
            j++;
    }
    return j; // После прохода по всему тексту j — это длина наибольшего префикса pat, который совпадает с суффиксом txt
}

// Функция strip_newline — удаляет завершающий '\n' из строки, возвращает новую длину
int strip_newline(char *s)
{
    int len = (int)strlen(s); // Вычисляем текущую длину строки. Приводим к int
    if (len > 0 && s[len - 1] == '\n') // Проверяем, есть ли в конце символ перевода строки.
    {
        s[len - 1] = '\0'; // заменяем его на \0 (конец строки)
        len--; // Уменьшаем длину на 1. Это нужно, потому что fgets сохраняет \n в буфере
    }
    return len; // Возвращаем новую длину строки
}

int main(void)
{
    static char s1[MAXLEN], s2[MAXLEN]; // Две строки для хранения ввода static нужен, чтобы большие массивы не размещались в стеке.

    if (fgets(s1, sizeof(s1), stdin) == NULL) // Если ввод закончился сразу (EOF) или произошла ошибка, fgets вернёт NULL
    {
        printf("0 0\n"); // Выводим 0 0
        return 0; // Завершаем программу
    }
    if (fgets(s2, sizeof(s2), stdin) == NULL) // То же для второй строки
    {
        printf("0 0\n");
        return 0;
    }

    // Убираем символы перевода строки из обеих строк и получаем их реальные длины
    int len1 = strip_newline(s1);
    int len2 = strip_newline(s2);

    int ans1 = kmp_match_end(s1, len1, s2, len2); // Ищем длину наибольшего префикса первой строки, который является суффиксом второй
    int ans2 = kmp_match_end(s2, len2, s1, len1); // Ищем длину наибольшего префикса второй строки, который является суффиксом первой.

    printf("%d %d\n", ans1, ans2); // Выводим два числа через пробел
    return 0;
}
