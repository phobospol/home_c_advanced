/*
Найти брата
В программе описано двоичное дерево:
typedef struct tree {
datatype key;
struct tree *left, *right;
struct tree *parent; //ссылка на родителя
} tree;
Требуется реализовать функцию, которая по ключу возвращает адрес соседнего элемента - брата. Если такого ключа нет или у узла нет брата, то необходимо вернуть 0.
Прототип функции: tree * findBrother(tree *root, int key)
*/

// Функция принимает указатель на корень дерева и искомый ключ. Возвращает указатель на узел-брат или NULL
tree *findBrother(tree *root, int key) 
{
    if (root == NULL) // Если дерево пустое — искать нечего 
        return NULL; // Возвращаем NULL

    // Динамический стек для итеративного DFS-поиска узла 
    int cap = 64;// Размер массива указателей на узлы дерева
    tree **stack = malloc(cap * sizeof(tree *));// Выделяем память под массив указателей на tree
    int top = 0; // Создаем — индекс вершины стека
    stack[top++] = root; // Помещаем корень в стек. Сначала используем значение top=0 как индекс, затем увеличиваем на 1

    tree *target = NULL; // Переменная, куда запишем найденный узел
    
    // Цикл поиска узла
    while (top > 0) // Пока стек не пуст — продолжаем поиск 
    {
        tree *node = stack[--top]; // Убираем элемент с вершины стека. Сначала уменьшаем top на 1, затем используем как индекс. node указывает на извлечённый узел

        if (node->key == key) // Сравниваем ключ текущего узла с искомым
        {
            target = node; // Если совпал — запоминаем узел в target
            break; // Выходим из цикла
        }

        if (node->right) // Проверяем, есть ли у узла правый потомок 
        {
			// Если стек заполнен (top >= cap) — удваиваем его размер. realloc перемещает массив в новый, более крупный блок памяти
            if (top >= cap) 
            {
                cap *= 2;
                stack = realloc(stack, cap * sizeof(tree *));
            }
            stack[top++] = node->right; // Кладём правого потомка в стек.
        }
        // Аалогично для левого потомка. Проверяем на переполнение и помещение в стек. Левый потомок кладётся последним, поэтому извлечётся первым — обход идёт слева направо
        if (node->left) 
        {
            if (top >= cap) 
            {
                cap *= 2;
                stack = realloc(stack, cap * sizeof(tree *));
            }
            stack[top++] = node->left;
        }
    }

    free(stack); // Освобождаем память

    // Узел не найден или это корень (нет родителя)
    if (target == NULL || target->parent == NULL) // Проверяем два случая, когда брата нет
        return NULL; // Возвращаем NULL

    // Поиск брата   
    tree *p = target->parent;  // Сохраняем указатель на родителя в переменную p
    // Проверяем является ли найденный узел левым потомком родителя. Сравниваем указатели
    if (p->left == target) // Если target — левый потомок, то его брат — правый потомок того же родителя
        return p->right; // Возвращаем p->right
    else
    // Иначе target — правый потомок, а его брат — левый.
        return p->left; // Возвращаем p->left
}
