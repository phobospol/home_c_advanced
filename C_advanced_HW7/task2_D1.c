/*
 Вид сверху
В программе описана структура для хранения двоичного дерева:
typedef struct tree {
datatype key;
struct tree *left, *right;
} tree;
Необходимо реализовать функцию, которая печатает вид дерева сверху. Функция должна строго соответствовать прототипу:

void btUpView(tree *root)
 */ 

// Функция принимает указатель на корень дерева
void btUpView(tree *root) 
{
    if (!root) return; // Если root равен NULL (дерево пустое) выходим

    /* Очередь для BFS на динамических массивах */
    int cap = 16; // Начальная вместимость очереди — 16 элементов. В ней будут храниться указатели на узлы и их горизонтальные дистанции
    tree **qnode = malloc(cap * sizeof(tree *)); // Выделяем память под массив указателей на tree.  Это массив узлов очереди — здесь будут лежать указатели на узлы дерева в порядке обхода BFS
    int   *qhd   = malloc(cap * sizeof(int)); // Выделяем память под массив целых чисел. Здесь будут лежать горизонтальные дистанции (HD), соответствующие узлам из qnode.
    int qf = 0, qr = 0; // Создаем два указателя очереди: qf (front) — индекс первого элемента (голова), qr (rear) — индекс следующего свободного места (хвост). 

    /* Корень — HD = 0 */
    qnode[qr] = root; // Записываем указатель на корень в первую ячейку массива узлов
    qhd[qr]   = 0; // Записываем HD корня — 0 (корень находится на центральной вертикали).
    qr++; // Сдвигаем хвост на 1. Теперь в очереди один элемент: qnode[0] = root, qhd[0] = 0

    int min_hd = 0, max_hd = 0; // Создаем переменные для диапазона HD (минимальная и максимальная HD)

    /* BFS: обход по уровням + поиск диапазона HD за один проход */
    while (qf < qr) // Пока голова не догнала хвост — в очереди есть необработанные элементы 
    {
        tree *t  = qnode[qf]; // Берём узел из головы очереди. 
        int   hd = qhd[qf]; // Берём его горизонтальную дистанцию.
        qf++; // Сдвигаем голову — элемент «извлечён» из очереди qf перешла дальше
       // Обновляем минимум и максимум HD. 
        if (hd < min_hd) min_hd = hd; // После обхода всего дерева min_hd будет самой левой вертикалью
        if (hd > max_hd) max_hd = hd; // max_hd — самой правой
      
        // Добавление левого потомка в очередь
        if (t->left) // Проверяем есть ли у текущего узла левый потомок
        {
            if (qr >= cap) // Если qr >= cap — места нет 
            {
                cap *= 2; // удваиваем cap
                // Перераспределяем память через realloc для обоих массивов.
                qnode = realloc(qnode, cap * sizeof(tree *)); 
                qhd   = realloc(qhd,   cap * sizeof(int));
            }
            qnode[qr] = t->left; // Записываем левого потомка в очередь
            qhd[qr]   = hd - 1; //  Его HD на 1 меньше родительской (сдвиг влево)
            qr++; // Сдвигаем хвост
        }
        
        // Добавление правого потомка в очередь, аналогично левому, но HD правого потомка на 1 больше родительской (сдвиг вправо).
        if (t->right) 
        {
            if (qr >= cap) 
            {
                cap *= 2;
                qnode = realloc(qnode, cap * sizeof(tree *));
                qhd   = realloc(qhd,   cap * sizeof(int));
            }
            qnode[qr] = t->right;
            qhd[qr]   = hd + 1;
            qr++;
        }
    }

    // Массивы для результата
    int       range = max_hd - min_hd + 1; // Количество различных вертикалей в дереве
    int      *seen  = calloc(range, sizeof(int)); // Массив-флаг: отмечаем, была ли уже использована данная вертикаль. calloc обнуляет память, все элементы равны 0
    datatype *top   = malloc(range * sizeof(datatype)); // Массив для хранения значений видимых сверху узлов. top[idx] — значение узла, видимого на вертикали с индексом idx.

    // Проходим по собранным узлам в BFS-порядке: первый узел для каждой HD — видимый сверху
    for (int i = 0; i < qr; i++) // Проходим по всем узлам в BFS-порядке — от верхних к нижним уровням.
    {
        int idx = qhd[i] - min_hd; //Вычисляем индекс в массивах. Сдвиг на −min_hd превращает самую левую HD в индекс 0 
        if (!seen[idx]) // Если вертикаль ещё не занята (seen[idx] == 0)
        {
            seen[idx] = 1; // отмечаем её как занятую 
            top[idx]  = qnode[i]->key; // записываем значение узла
        }
    }

    // Печать слева направо. Проходим по массиву top слева направо (от минимальной HD к максимальной) и печатаем значения.
    for (int i = 0; i < range; i++) 
    {
        if (seen[i])
            printf("%d ", top[i]);
    }
    printf("\n");
    
    // Освобождение памяти. Освобождаем все четыре динамических массива.
    free(seen);
    free(top);
    free(qnode);
    free(qhd);
}
