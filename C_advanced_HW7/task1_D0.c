#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/*
Отсортировать слова
Дана строка, состоящая из английских букв и пробелов. В конце строки символ точка. Все слова разделены одним пробелом. Необходимо составить из слов односвязный список и упорядочить по алфавиту. Список необходимо удалить в конце программы. Для сравнение строк можно использовать strcmp. Необходимо использовать данную структуры организации списка.
struct list {
char word[20];
struct list *next;
}
Необходимо реализовать односвязный список и обслуживающие его функции.

add_to_list
 swap_elements
 print_list
 delete_list
*/

// Создаем структуру с тегом list
struct list
{
    char word[20]; // Поле word — массив из 20 символов. В нём хранится само слово
    struct list *next; // Поле next — указатель на следующий узел списка
};

// Функция add_to_list принимает указатель на голову списка (head) и строку с новым словом (word) и возвращает указатель на голову
struct list *add_to_list(struct list *head, const char *word)
{
    struct list *node = malloc(sizeof(struct list)); // Выделяем память под один узел списка
    if (node == NULL) // Проверяем, не вернул ли malloc значение NULL
    {
        fprintf(stderr, "Memory allocation error\n"); //Печатаем сообщение об ошибке в поток stderr
        exit(1);
    }
    strncpy(node->word, word, sizeof(node->word) - 1); // Копируем слово из аргумента word в поле node->word. Ограничиваем длину до 19 символов, оставляя один байт для нуль-терминатора
    node->word[sizeof(node->word) - 1] = '\0'; // Принудительно ставим нуль-терминатор в последнюю позицию массива. Если слово оказалось длиннее 19 символов
    node->next = NULL; // Новый узел будет последним, поэтому указатель на следующий элемент устанавливаем в NULL.

    if (head == NULL) // Проверяем, пуст ли список.
        return node; // Если список был пуст, новый узел становится головой. Возвращаем его.

    struct list *cur = head; // Создаём временный указатель cur и начинаем с головы списка. С его помощью пройдём до конца.
    while (cur->next != NULL) // Пока текущий узел не последний
        cur = cur->next; // переходим к следующему узлу
    cur->next = node; // Присоединяем новый узел к последнему элементу
    return head; // Возвращаем указатель на голову
}

// Функция swap_elements принимает два указателя на узлы. Меняет местами их содержимое (слова), а не сами указатели.
void swap_elements(struct list *a, struct list *b)
{
    char tmp[20]; // Создаём временный массив для хранения слова при обмене
    strncpy(tmp, a->word, sizeof(tmp) - 1); // Копируем слово из первого узла во временную переменную.
    tmp[sizeof(tmp) - 1] = '\0';
    strncpy(a->word, b->word, sizeof(a->word) - 1); // Копируем слово из второго узла в первый
    a->word[sizeof(a->word) - 1] = '\0';
    strncpy(b->word, tmp, sizeof(b->word) - 1); // Копируем сохранённое слово из временной переменной во второй узел
    b->word[sizeof(b->word) - 1] = '\0';
}

// Функция print_list принимает указатель на голову списка и печатает все слова
void print_list(struct list *head)
{
    struct list *cur = head; // Создаём временный указатель и начинаем с головы
    while (cur != NULL) // Пока не достигли конца списка
    {
        printf("%s", cur->word); // печатаем слово из текущего узла
        if (cur->next != NULL) // Проверяем, есть ли следующий элемент
            printf(" "); // Если есть — печатаем пробел между словами
        cur = cur->next; // Переходим к следующему узлу.
    }
    printf("\n"); // После печати всех слов выводим перевод строки
}

// Функция delete_list принимает указатель на голову списка и освобождает всю память
void delete_list(struct list *head)
{
    struct list *cur = head;
    while (cur != NULL) {
        struct list *next = cur->next; // сохраняем указатель на следующий узел во временную переменную next после free(cur) уже не сможем прочитать cur->next.
        free(cur); // Освобождаем память текущего узла
        cur = next; // Переходим к следующему узлу который заранее сохранили
    }
}

// Функция sort_list принимает указатель на голову и сортирует список по алфавиту пузырьком
void sort_list(struct list *head)
{
    if (head == NULL) // Проверяем, не пуст ли список
        return;

    int swapped; // Переменная-флаг: были ли обмены на текущем проходе
    struct list *cur; // Указатель для прохода по списку.
    struct list *last = NULL; // Указатель на последний обработанный элемент

    do
    {
        swapped = 0;
        cur = head;
        while (cur->next != last) // Идём до элемента, предшествующего last. На первом проходе last == NULL, поэтому проходим весь список
        {
            if (strcmp(cur->word, cur->next->word) > 0) // Сравниваем текущее слово со следующим. strcmp возвращает число больше нуля, если текущее слово лексикографически больше следующего (то есть стоит по алфавиту позже)
            {
                swap_elements(cur, cur->next); // Меняем слова местами
                swapped = 1; //  Был обмен — нужен ещё один проход
            }
            cur = cur->next; // Переходим к следующему узлу
        }
        last = cur; //  cur указывает на последний сравниваемый элемент
    } while (swapped); // Если был хотя бы один обмен — повторяем. Если небыло выходим
}

int main(void)
{
    char str[1000]; // Буфер для входной строки

    // printf("Enter string: "); // Приглашение для ввода строки
    
    if (fgets(str, sizeof(str), stdin) == NULL) //Считываем строку из стандартного ввода (stdin) в буфер str и проверяем вернул ли NULL 
        return 1;

    str[strcspn(str, "\n")] = '\0'; // strcspn находит позицию первого '\n' в строке, и мы заменяем его на '\0', удаляя перевод строки

    /* Разбираем строку на слова */
    struct list *head = NULL; // Объявляем указатель на голову списка и инициализируем NULL
    char *token = strtok(str, " ."); // strtok разбивает строку на токены (слова) по разделителям — пробелу и точке
    while (token != NULL) // Пока strtok возвращает очередное слово
    {
        head = add_to_list(head, token); // добавляем слово в список. head переприсваиваем
        token = strtok(NULL, " ."); // Следующий вызов strtok с NULL вместо строки — он продолжает с того места, где остановился, и возвращает следующее слово
    }

    // printf("Original list:\n"); // Печатаем заголовок
    // print_list(head); // Печатаем список до сортировки

    sort_list(head); // Сортируем список по алфавиту

    // printf("Sorted list:\n");
    print_list(head); // Печатаем отсортированный список

    delete_list(head); // Освобождаем всю память, занятую списком
    head = NULL; // Устанавливаем указатель в NULL

    return 0;
}

