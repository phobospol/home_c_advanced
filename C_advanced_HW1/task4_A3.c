#include <stdio.h>
#include <stdint.h>
#include <inttypes.h>

/*
Извлечение бит
На вход программе подается беззнаковое 32-битное целое число N и натуральное число K (1 ≤ K ≤ 31). Требуется взять K младших битов числа N и вывести полученное таким образом число.
 */

int main()
{
    uint32_t n;
    int k;

    // Читаем n и k
    if (scanf("%" SCNu32 " %d", &n, &k) != 2)
    {
        return 1;
    }

    // По условию 1 ≤ k ≤ 31, но для надёжности ограничиваем диапазон
    if (k < 1 || k > 31)
    {
        // Можно вывести ошибку или просто нормализовать — здесь выходим с ошибкой
        return 1;
    }

    // Создаём маску из k единиц в младших разрядах: (1U << k) - 1, где 1U- один беззнаковый бит; 1U << k создаёт число, у которого ровно один бит установлен в 1 — на позиции k (считая с 0). Все остальные биты — нули; (1U << k) - 1 превращает этот бит и все старшие в нули, а все биты справа от него (то есть младшие k бит) становятся единицами.
    // Затем применяем побитовое И к n — остаются только младшие k бит
    uint32_t result = n & ((1U << k) - 1);

    printf("%" PRIu32 "\n", result);
    return 0;
}



