#include <stdio.h>

/*
Весы
В стартер боксе Geek Brains есть электронные чашечные весы (вместимость каждой чашки 1 тонна) и гири массами 1г, 3г, 9г, 27г, и т.д. по одной штуке каждой массы. Менеджер из рекламного отдела взял такие весы и не знает, можно ли взвесить что-нибудь тяжелое и если можно, сколько гирь придется положить на весы (на любую чашку). Надо помочь ему. Формат входных данных: единственное натуральное число – масса взвешиваемого товара в граммах (не больше 1000000000). Формат выходных данных: единственное целое число – общее количество гирь или число –1 если данный товар взвесить невозможно.
 */

int main()
{
    long long m;
    if (scanf("%lld", &m) != 1)
    {
        return 1;
    }

    const long long LIMIT = 1000000LL;  // 1 тонна в граммах

    // Если сам товар тяжелее 1 тонны — сразу невозможно
    if (m > LIMIT)
    {
        printf("-1\n");
        return 0;
    }

    long long n = m;
    long long left_sum = 0;   // сумма гирь на чаше с товаром (или сам товар, если считать его "левой")
    long long right_sum = 0;  // сумма гирь на противоположной чаше
    int count = 0;

    long long power_of_3 = 1; // текущая масса гири: 3^0, 3^1, ...

    while (n > 0)
    {
        int rem = n % 3;

        if (rem == 0)
        {
            // Гиря не используется
            n /= 3;
        } else if (rem == 1)
        {
            // Используем гирю на противоположной чаше (добавляем к right_sum)
            count++;
            right_sum += power_of_3;
            n /= 3;
        } else { // rem == 2
            // Эквивалентно -1: гиря кладётся на чашу с товаром (добавляем к left_sum)
            // и делаем перенос: n = n/3 + 1
            count++;
            left_sum += power_of_3;
            n = n / 3 + 1;
        }

        // Проверка лимита после каждого шага
        // На левой чаше: товар + гири, которые мы положили туда (left_sum)
        // Но в нашей модели left_sum — это только гири на той же чаше, что и товар.
        // Сам товар m уже лежит на этой чаше.
        if (m + left_sum > LIMIT || right_sum > LIMIT)
        {
            printf("-1\n");
            return 0;
        }

        power_of_3 *= 3;
    }

    printf("%d\n", count);
    return 0;
}


