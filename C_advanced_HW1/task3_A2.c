#include <stdio.h>
#include <inttypes.h>

/*
Циклический сдвиг
На вход программе подается беззнаковое 32-битное целое число N и натуральное число K (1 ≤ K ≤ 31). Требуется циклически сдвинуть биты числа N вправо на K битов и вывести полученное таким образом число.
*/

int main()
{
    uint32_t n; // uint32_t для платформонезависимости
    int k;

    // Читаем n и k
    if (scanf("%" SCNu32 " %d", &n, &k) != 2) // Проверка != 2 гарантирует, что успешно считаны оба значения
    {
        return 1;
    }

    // По условию 1 ≤ K ≤ 31, но для надёжности ограничиваем сдвиг диапазоном 0–31 (исключение неопределенного поведения при сдвиге на 32
    k = k % 32; // Нормализация сдвига
    if (k == 0)
    {
        // Сдвиг на 0 или на кратное 32 — число не меняется
        printf("%" PRIu32 "\n", n);
        return 0;
    }

    // Циклический сдвиг вправо на k бит для 32-битного числа:
    // биты, ушедшие вправо, должны появиться слева
    uint32_t right_part = n >> k;                 // часть, которая сдвигается вправо
    uint32_t left_part  = n << (32 - k);           // часть, которая «вылезает» слева
    uint32_t result     = right_part | left_part;  // побитовое ИЛИ объединяет две части

    printf("%" PRIu32 "\n", result); // PRIu32 для корректного вывода результата на любой платформе
    return 0;
}
