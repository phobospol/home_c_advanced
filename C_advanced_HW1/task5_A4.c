#include <stdio.h>
#include <stdint.h>
#include <inttypes.h>

/*
Поиск последовательности бит
На вход программе подается беззнаковое 32-битное целое число N и натуральное число K (1 ≤ K ≤ 31). Требуется взять K подряд идущих битов числа N так, чтобы полученное число было максимальным. Программа должна вывести полученное число.
 */

int main()
{
    uint32_t n;
    int k;

    // Читаем N и K
    if (scanf("%" SCNu32 " %d", &n, &k) != 2)
    {
        return 1;
    }

    // Проверка диапазона K: по условию 1 ≤ K ≤ 31
    if (k < 1 || k > 31)
    {
        return 1;
    }

    uint32_t max_val = 0;

    // Перебираем все возможные позиции начала окна из k бит (от 0 до 32-k)
    for (int start = 0; start <= 32 - k; ++start)
    {
        // Создаём маску для k бит, начинающихся с позиции start
        uint32_t mask = ((1U << k) - 1) << start;

        // Извлекаем эти k бит из n и сдвигаем их в младшие разряды
        uint32_t window = (n & mask) >> start;

        // Сравниваем с текущим максимумом
        if (window > max_val)
        {
            max_val = window;
        }
    }

    printf("%" PRIu32 "\n", max_val);
    return 0;
}
